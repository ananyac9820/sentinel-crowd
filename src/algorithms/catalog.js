// One place that describes every algorithm the decision engine actually calls.
// The UI reads this for the complexity panel; the `file` field points at the implementation.
export const ALGORITHMS = {
  mergeSort: {
    name: 'Merge sort',
    purpose: 'Rank zones from most to least dangerous',
    time: 'O(n log n)',
    space: 'O(n)',
    structure: 'Arrays (merge buffers)',
    file: 'src/algorithms/sorting/mergeSort.js',
    viva: 'Ranks crowd zones in O(n log n) in every case. It is stable, so zones with equal density keep their camera order, which makes the ranking reproducible.',
  },
  binarySearch: {
    name: 'Binary search',
    purpose: 'Find each zone’s alert band in the sorted thresholds',
    time: 'O(log n)',
    space: 'O(1)',
    structure: 'Sorted array of thresholds',
    file: 'src/algorithms/searching/binarySearch.js',
    viva: 'The WATCH / WARNING / CRITICAL limits are sorted, so the band for a density is found by halving the range each probe instead of checking every limit.',
  },
  graph: {
    name: 'Graph construction',
    purpose: 'Turn the crowd state into a weighted graph',
    time: 'O(V + E)',
    space: 'O(V + E)',
    structure: 'Adjacency list',
    file: 'src/engine/crowdGraphBuilder.js',
    viva: 'Zones, exits, stairs and station areas become nodes; walkable connections become edges carrying distance, capacity, congestion, risk and cost. An adjacency list suits this sparse graph.',
  },
  bfs: {
    name: 'Breadth-first search',
    purpose: 'Which exits can the critical zone still reach?',
    time: 'O(V + E)',
    space: 'O(V)',
    structure: 'Queue',
    file: 'src/algorithms/graph/bfs.js',
    viva: 'Used to determine reachability through the crowd network. Closed gates have zero capacity and are skipped, so a locked exit shows up as unreachable.',
  },
  dfs: {
    name: 'Depth-first search',
    purpose: 'Which connected zones are affected by the dangerous zone?',
    time: 'O(V + E)',
    space: 'O(V)',
    structure: 'Stack (explicit)',
    file: 'src/algorithms/graph/dfs.js',
    viva: 'Explores the connected region of zones already at WATCH or above around the critical zone. That cluster is the area stewards must manage together.',
  },
  dijkstra: {
    name: 'Dijkstra',
    purpose: 'Safest evacuation route from the critical zone',
    time: 'O((V + E) log V)',
    space: 'O(V + E)',
    structure: 'Binary min-heap (priority queue)',
    file: 'src/algorithms/graph/dijkstra.js',
    viva: 'Used because evacuation costs are never negative. Each edge cost combines distance, congestion and risk, so the safest route can be longer than the shortest one.',
  },
  maxFlow: {
    name: 'Max flow (Edmonds-Karp)',
    purpose: 'Evacuation capacity in people per minute',
    time: 'O(V · E²)',
    space: 'O(V + E)',
    structure: 'Residual graph + queue (BFS)',
    file: 'src/algorithms/flow/maxFlow.js',
    viva: 'Crowd movement through corridors behaves like flow through capacity-limited edges. Edmonds-Karp always augments along the shortest path (BFS), which bounds it to O(V·E²).',
  },
  minCut: {
    name: 'Min cut',
    purpose: 'Bottleneck that limits evacuation',
    time: 'O(V + E) after max flow',
    space: 'O(V)',
    structure: 'Residual graph + queue (BFS)',
    file: 'src/algorithms/flow/minCut.js',
    viva: 'By the max-flow min-cut theorem, the saturated edges leaving the residual-reachable set limit the total flow. Only adding capacity to the cut can raise evacuation capacity.',
  },
  greedy: {
    name: 'Greedy intervention selection',
    purpose: 'Fast plan: best benefit / cost first',
    time: 'O(m² · T_flow), T_flow = O(V · E²)',
    space: 'O(m)',
    structure: 'Array of candidate actions',
    file: 'src/algorithms/optimization/greedyIntervention.js',
    viva: 'Repeatedly takes the action with the best seconds-saved per cost, measured by re-running max flow. It is fast and locally optimal but not guaranteed to be globally optimal.',
  },
  backtracking: {
    name: 'Backtracking planner',
    purpose: 'Exact best plan within the budget (checks greedy)',
    time: 'O(2^m · T_flow)',
    space: 'O(m) recursion',
    structure: 'Recursion (implicit stack)',
    file: 'src/algorithms/optimization/backtrackingPlanner.js',
    viva: 'Tries every include / exclude choice and prunes branches that break the budget. Exponential in the number of actions, which is why greedy is used for the live decision.',
  },
}
