    time: { best: 'O(V + E)', average: 'O(V + E)', worst: 'O(V + E)' },
    space: 'O(V)',
    why: 'On an unweighted view, the first time BFS reaches a node it has done so with the fewest edges. Fewest transitions is the honest answer to "how many areas must these people cross?", and every extra transition is another chance for the crowd to stall. BFS also proves reachability: a zone it never reaches has no route out at all.',
    notInstead: 'Dijkstra answers a weighted question and costs an extra log factor; it cannot report hop counts. DFS reaches the same nodes but by no particular distance.',
